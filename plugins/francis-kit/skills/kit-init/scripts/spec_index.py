#!/usr/bin/env python3
"""Write specs/INDEX.md: one row per feature, read from each spec.md.

    spec_index.py [--root DIR]            write the index
    spec_index.py [--root DIR] --check    exit 1 when the file on disk is stale

The index is generated. Edit the specs, then run this again.
Exit 0 written or current, 1 stale under --check, 2 no specs/ directory.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kit_spec  # noqa: E402

FEATURE_DIR = kit_spec.FEATURE_DIR
TITLE = re.compile(r'^#[ \t]+(.+?)[ \t]*$', re.M)
HEADER = '<!-- generated by spec_index.py from each spec.md; do not edit -->'


def field(name, text):
    found = kit_spec.fields(name, text)
    return found[0] if found else '-'


def status_cell(text):
    """The valid Status, else the project's own wording; never a valid word the doctor would not accept."""
    raw = field('Status', text)
    return kit_spec.status(text) or ('-' if raw in kit_spec.STATUSES + kit_spec.ENDED else raw)


def cell(value):
    return value.replace('|', '\\|').strip() or '-'


def build(specs: Path) -> str:
    rows = []
    for entry in sorted(specs.iterdir()):
        if not entry.is_dir() or not FEATURE_DIR.match(entry.name):
            continue
        spec = entry / 'spec.md'
        text = kit_spec.read(spec) or ''
        title = TITLE.search(kit_spec.COMMENT.sub('', kit_spec.body(text)))     # a commented-out title is no title
        rows.append('| [{0}]({0}/spec.md) | {1} | {2} | {3} | {4} | {5} |'.format(
            entry.name, cell(title.group(1) if title else '-'), cell(status_cell(text)),
            cell(field('Ticket', text)), cell(field('Capability', text)),
            sum(i.startswith('FR-') for i in kit_spec.requirements(text))))
    return '\n'.join([HEADER, '', '# Feature index', '',
                      '| Feature | Title | Status | Ticket | Capability | FR |',
                      '|---|---|---|---|---|---|', *rows]) + '\n'

def write(path, text):
    """Replace the index in one step."""
    kit_spec.replace(path, text.encode('utf-8'))    # encoding fails here, before the old index is touched


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--root', default='.')
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args(argv)
    specs = Path(args.root).resolve() / 'specs'
    if not specs.is_dir():
        print(f'{specs} is missing')
        return 2
    wanted = build(specs)
    target = specs / 'INDEX.md'
    if target.is_symlink():
        print('specs/INDEX.md is a symlink, which is neither read nor written')
        return 2
    current = target.read_text(encoding='utf-8-sig', errors='replace') if target.is_file() else None
    if args.check:
        if current != wanted:
            print('specs/INDEX.md is stale: run spec_index.py')
            return 1
        print('specs/INDEX.md is current')
        return 0
    if current != wanted:
        try:
            write(target, wanted)
        except (OSError, UnicodeError) as exc:
            print(f'specs/INDEX.md could not be written: {type(exc).__name__}: {exc}')
            return 2
    print(f'specs/INDEX.md: {wanted.count(chr(10)) - 6} feature(s)')
    return 0


if __name__ == '__main__':
    for _stream in (sys.stdout, sys.stderr):   # a Windows console is not UTF-8 by default
        try:
            _stream.reconfigure(encoding='utf-8', errors='replace')
        except (AttributeError, ValueError, OSError):
            pass
    try:
        sys.exit(main())
    except Exception as exc:      # a crash is "nothing was checked", never a verdict
        print(f'spec_index.py could not finish: {type(exc).__name__}: {exc}', file=sys.stderr)
        sys.exit(2)
